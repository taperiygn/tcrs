#!/usr/bin/env python3
"""Generate the TRIPS + ALIAS tables for frontend/clash.js from the
school's trip-time matrix workbook (trplfttimes.xlsx).

The workbook is a symmetric matrix: column A holds the row labels, row 1
holds the column headers. Grouped headers ("FC Site 1/CCP 1/CCP 2") mean
those names are the SAME place; "300m Range" duplicates "BIC Range" and
"HG Range" duplicates "100m Range" (verified: identical rows/columns).

Run from the repo root:  python3 tools/gen_trips.py <path-to-xlsx>
Paste the output into frontend/clash.js (replacing TRIPS and ALIAS).
"""
import re
import sys
import zipfile
import xml.etree.ElementTree as ET

NS = '{http://schemas.openxmlformats.org/spreadsheetml/2006/main}'
COLS = 'BCDEFGHIJKLMNOPQRSTUV'


def norm(s):
    return re.sub(r'\s+', ' ', str(s).strip()).upper()


def load(path):
    z = zipfile.ZipFile(path)
    shared = [''.join(t.text or '' for t in si.iter(NS + 't'))
              for si in ET.fromstring(z.read('xl/sharedStrings.xml')).findall(NS + 'si')]
    sheet = ET.fromstring(z.read('xl/worksheets/sheet1.xml'))
    grid = {}
    for row in sheet.iter(NS + 'row'):
        r = int(row.get('r'))
        for c in row.iter(NS + 'c'):
            ref = c.get('r')
            v = c.find(NS + 'v')
            val = v.text if v is not None else ''
            if c.get('t') == 's' and val != '':
                val = shared[int(val)]
            grid[(r, ref[0])] = val
    return grid


def main(path):
    grid = load(path)
    headers = {col: norm(grid[(1, col)]) for col in COLS}

    # canonical place per column: first name of its header group;
    # "300m Range" is the same place as "BIC Range" (identical data)
    canon_of_col = {}
    for col, h in headers.items():
        canon_of_col[col] = canon_of_col.get('_canon:' + h.split('/')[0]) or norm(h.split('/')[0])
    canon_of_col['E'] = canon_of_col['D']          # 300m Range == BIC Range

    # alias map: every name in a group -> the group's canonical place
    alias = {}
    for col, h in headers.items():
        for part in h.split('/')[1:]:
            alias[norm(part)] = canon_of_col[col]
    alias['300M RANGE'] = canon_of_col['D']
    alias['SIT SITE 1'] = 'SITEST SITE 1'          # seen in the live data

    # row labels -> their column (by name match against header groups)
    row_of_col = {}
    for r in range(2, 24):
        name = norm(grid[(r, 'A')])
        if not name:
            continue
        for col, h in headers.items():
            if name in [norm(p) for p in h.split('/')]:
                row_of_col.setdefault(canon_of_col[col], r)
                break
        else:
            raise SystemExit('row %d label %r matches no header group' % (r, name))

    missing = [c for c in canon_of_col.values() if c not in row_of_col]
    if missing:
        raise SystemExit('no row label for canonical place(s): %s' % sorted(set(missing)))

    # pairwise durations, read at (row of a, column of b); verify symmetry
    places = sorted(row_of_col)
    pairs = {}
    for i, a in enumerate(places):
        for b in places[i + 1:]:
            v_ab = float(grid[(row_of_col[a], canon_col(canon_of_col, headers, b))])
            v_ba = float(grid[(row_of_col[b], canon_col(canon_of_col, headers, a))])
            if v_ab != v_ba:
                raise SystemExit('asymmetric pair %s/%s: %s vs %s' % (a, b, v_ab, v_ba))
            pairs[(a, b)] = int(v_ab)

    print('/* %d canonical places, %d pairs — generated by tools/gen_trips.py' % (len(places), len(pairs)))
    print('   from the school trip-time matrix (trplfttimes.xlsx); returns take')
    print('   the same time. Do not hand-edit: regenerate instead. */')
    print('var TRIPS = {')
    for (a, b), v in sorted(pairs.items()):
        print("    '%s|%s': %d," % (a, b, v))
    print("    /* not in the matrix — timed by hand */")
    print("    'RHC|S1': 15,")
    print('};')
    print()
    print('var ALIAS = {')
    for k, v in sorted(alias.items()):
        print("    '%s': '%s'," % (k, v))
    print('};')


def canon_col(canon_of_col, headers, place):
    """the matrix column whose canonical place is `place`"""
    for col in COLS:
        if canon_of_col[col] == place:
            return col
    raise SystemExit('no column for place %r' % place)


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '/Users/reliygn/Downloads/trplfttimes.xlsx')
